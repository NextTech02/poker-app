/**
 * Ícone de traço (outline) reutilizável.
 *
 * O tamanho e a cor vêm do CSS de quem usa (ex.: `.cx-header-icon svg`), então
 * por padrão o SVG não fixa dimensão nem cor: usa `currentColor` no traço.
 * `stroke-width` fica travado em 2 com viewBox 0 0 24 24 — mudar isso deixa o
 * traço fino ou grosso demais conforme o tamanho renderizado.
 *
 * Por padrão é decorativo (`aria-hidden`), porque nos cabeçalhos o título ao
 * lado já nomeia a página; passe `title` quando o ícone precisar ser anunciado.
 */
function Icon({ name, className, title, ...rest }) {
  const path = ICON_PATHS[name];
  if (!path) return null;

  const decorativo = !title;

  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={decorativo ? 'true' : undefined}
      role={decorativo ? undefined : 'img'}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      <path d={path} />
    </svg>
  );
}

export default React.memo(Icon);
