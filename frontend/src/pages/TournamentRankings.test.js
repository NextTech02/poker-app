/**
 * Ranking do torneio — a ordem de saída vira a classificação final.
 *
 * A posição é derivada da hora da eliminação, então o RECÁLCULO é a operação
 * que conserta a lista depois de qualquer correção (um rebuy tardio, uma
 * eliminação registrada fora de ordem). Sem ele, a única saída seria mexer no
 * banco.
 *
 * "Sem ninguém eliminado" não é erro: é o estado normal de um torneio em
 * andamento, e a tela precisa dizer isso em vez de mostrar uma tabela vazia.
 */
import { render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';
import TournamentRankings from './TournamentRankings';
import api from '../config/api';
import { useToast } from '../contexts/ToastContext';
import { useCurrency } from '../contexts/CurrencyContext';

jest.mock('../config/api', () => ({
  __esModule: true,
  default: { get: jest.fn(), post: jest.fn() },
}));
jest.mock('../components/Sidebar', () => () => <nav data-testid="sidebar" />);
jest.mock('../contexts/ToastContext', () => ({ useToast: jest.fn() }));
jest.mock('../contexts/CurrencyContext', () => ({ useCurrency: jest.fn() }));
const mockNavigate = jest.fn();
jest.mock('react-router-dom', () => ({
  ...jest.requireActual('react-router-dom'),
  useParams: () => ({ tournamentId: 't1' }),
  useNavigate: () => mockNavigate,
}));
jest.mock('react-i18next', () => {
  const t = (chave, vars) =>
    vars && typeof vars === 'object' ? `${chave}:${Object.values(vars).join(',')}` : chave;
  const traducao = { t, i18n: { language: 'pt-BR' } };
  return { useTranslation: () => traducao };
});

const TORNEIO = { id: 't1', name: 'Main Event' };

const RANKINGS = [
  { player_id: 'p1', position: 1, player_name: 'Ana', player_nickname: 'Aninha',
    status: 'winner', eliminated_at: null, prize_won: 20000 },
  { player_id: 'p2', position: 2, player_name: 'Beto', status: 'eliminated',
    eliminated_at: '2026-06-09T02:30:00Z', prize_won: 10000 },
  { player_id: 'p3', position: 3, player_name: 'Carla', status: 'eliminated',
    eliminated_at: '2026-06-09T02:00:00Z', prize_won: 0 },
  { player_id: 'p4', position: 4, player_name: 'Davi', status: 'desistiu',
    eliminated_at: '2026-06-09T01:00:00Z', prize_won: 0 },
];

let toast;

const responder = ({ torneio = TORNEIO, rankings = RANKINGS } = {}) => {
  api.get.mockImplementation((url) => {
    if (url === '/tournaments/t1') {
      return torneio instanceof Error ? Promise.reject(torneio) : Promise.resolve({ data: torneio });
    }
    if (url === '/rankings/tournament/t1') {
      return rankings instanceof Error ? Promise.reject(rankings) : Promise.resolve({ data: rankings });
    }
    return Promise.resolve({ data: [] });
  });
};

const montar = async (opcoes) => {
  responder(opcoes);
  render(<MemoryRouter><TournamentRankings /></MemoryRouter>);
  await waitFor(() => expect(screen.queryByText('common.loading')).toBeNull());
};

const linhaDe = (nome) =>
  Array.from(document.querySelectorAll('.rankings-table tbody tr')).find((tr) =>
    within(tr).queryByText(nome)
  );

beforeEach(() => {
  toast = { success: jest.fn(), error: jest.fn(), warning: jest.fn() };
  useToast.mockReturnValue({ toast });
  useCurrency.mockReturnValue({ formatCurrency: (v) => `R$ ${Number(v || 0).toFixed(2)}` });
  api.post.mockResolvedValue({ data: {} });
  jest.spyOn(console, 'error').mockImplementation(() => {});
});

afterEach(() => console.error.mockRestore());

describe('carga', () => {
  it('mostra o carregamento antes dos dados', () => {
    api.get.mockReturnValue(new Promise(() => {}));
    render(<MemoryRouter><TournamentRankings /></MemoryRouter>);
    expect(screen.getByText('common.loading')).toBeInTheDocument();
  });

  it('o subtítulo diz o torneio e quantos já saíram', async () => {
    await montar();
    expect(document.querySelector('.subtitle')).toHaveTextContent('Main Event,4');
  });

  it('sem eliminado nenhum, explica que é o estado normal', async () => {
    // Uma tabela vazia pareceria erro de carregamento.
    await montar({ rankings: [] });
    expect(screen.getByText('tournamentRankings.noEliminatedYet')).toBeInTheDocument();
    expect(screen.getByText('tournamentRankings.rankingsAutoGenerated')).toBeInTheDocument();
  });

  it('falha ao carregar não deixa a tela presa', async () => {
    await montar({ torneio: new Error('500') });
    expect(screen.queryByText('common.loading')).toBeNull();
  });

  it('voltar leva à lista de torneios', async () => {
    await montar();
    await userEvent.click(screen.getByRole('button', { name: 'common.back' }));
    expect(mockNavigate).toHaveBeenCalledWith('/torneios');
  });
});

describe('a tabela', () => {
  it('o pódio ganha medalha em vez de número', async () => {
    // É a leitura instantânea de quem ganhou, útil no telão e na conferência.
    await montar();
    expect(within(linhaDe('Ana')).getByText('🥇')).toBeInTheDocument();
    expect(within(linhaDe('Beto')).getByText('🥈')).toBeInTheDocument();
    expect(within(linhaDe('Carla')).getByText('🥉')).toBeInTheDocument();
  });

  it('fora do pódio, a posição é o número', async () => {
    await montar();
    expect(within(linhaDe('Davi')).getByText('4')).toBeInTheDocument();
  });

  it('o apelido aparece junto do nome', async () => {
    await montar();
    expect(within(linhaDe('Ana')).getByText('(Aninha)')).toBeInTheDocument();
  });

  it('o campeão é marcado como campeão, não como eliminado', async () => {
    // Ele não foi eliminado — foi o último de pé.
    await montar();
    expect(within(linhaDe('Ana')).getByText('tournamentRankings.statusWinner')).toBeInTheDocument();
    expect(within(linhaDe('Beto')).getByText('tournamentRankings.statusEliminated')).toBeInTheDocument();
  });

  it('status desconhecido aparece como veio', async () => {
    await montar();
    expect(within(linhaDe('Davi')).getByText('desistiu')).toBeInTheDocument();
  });

  it('quem não foi eliminado não mostra hora, mostra travessão', async () => {
    await montar();
    expect(within(linhaDe('Ana')).getAllByText('-').length).toBeGreaterThan(0);
  });

  it('prêmio zero vira travessão, não "R$ 0,00"', async () => {
    // "R$ 0,00" sugere prêmio pago de zero; travessão diz que não houve.
    await montar();
    expect(within(linhaDe('Carla')).getByText('-')).toBeInTheDocument();
    expect(within(linhaDe('Ana')).getByText('R$ 20000.00')).toBeInTheDocument();
  });
});

describe('recalcular', () => {
  it('recalcular reordena e recarrega a lista', async () => {
    // É o conserto depois de um rebuy tardio ou de uma eliminação fora de
    // ordem; sem ele só sobraria mexer no banco.
    await montar();
    const antes = api.get.mock.calls.length;
    await userEvent.click(screen.getByRole('button', { name: 'tournamentRankings.recalculate' }));
    await waitFor(() =>
      expect(api.post).toHaveBeenCalledWith('/rankings/tournament/t1/recalculate')
    );
    expect(toast.success).toHaveBeenCalledWith('tournamentRankings.recalculatedSuccess');
    await waitFor(() => expect(api.get.mock.calls.length).toBeGreaterThan(antes));
  });

  it('erro no recálculo mostra o motivo do servidor', async () => {
    const e = new Error('400');
    e.response = { data: { detail: 'Torneio ainda em andamento' } };
    api.post.mockRejectedValue(e);
    await montar();
    await userEvent.click(screen.getByRole('button', { name: 'tournamentRankings.recalculate' }));
    await waitFor(() =>
      expect(toast.error).toHaveBeenCalledWith('tournamentRankings.errorRecalculate:Torneio ainda em andamento')
    );
  });

  it('erro sem detalhe usa a mensagem da exceção', async () => {
    api.post.mockRejectedValue(new Error('Network Error'));
    await montar();
    await userEvent.click(screen.getByRole('button', { name: 'tournamentRankings.recalculate' }));
    await waitFor(() =>
      expect(toast.error).toHaveBeenCalledWith('tournamentRankings.errorRecalculate:Network Error')
    );
  });
});
